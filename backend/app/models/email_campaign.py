"""News e-mail campaigns sent by app administrators.

A campaign keeps the structured blocks it was rendered from, never raw HTML,
so a send can be re-rendered and audited. Deliveries make retries resumable:
a user who already received a campaign is never mailed it twice.
"""

from datetime import UTC, datetime
from uuid import UUID, uuid4

from sqlalchemy import JSON, DateTime, ForeignKey, Integer, String, Text, UniqueConstraint, Uuid
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class EmailCampaign(Base):
    __tablename__ = "email_campaigns"

    # Generated by the client so a retried send is idempotent.
    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True)
    created_by_user_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    locale: Mapped[str] = mapped_column(String(8))
    subject: Mapped[str] = mapped_column(String(160))
    preheader: Mapped[str] = mapped_column(String(200), default="")
    blocks: Mapped[list[dict[str, str]]] = mapped_column(JSON)
    recipient_count: Mapped[int] = mapped_column(Integer, default=0)
    sent_count: Mapped[int] = mapped_column(Integer, default=0)
    failed_count: Mapped[int] = mapped_column(Integer, default=0)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC), index=True
    )
    finished_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True), nullable=True)


class EmailCampaignDelivery(Base):
    __tablename__ = "email_campaign_deliveries"
    __table_args__ = (
        UniqueConstraint("campaign_id", "user_id", name="uq_email_delivery_campaign_user"),
    )

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    campaign_id: Mapped[UUID] = mapped_column(
        ForeignKey("email_campaigns.id", ondelete="CASCADE"), index=True
    )
    user_id: Mapped[UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    # sent | failed | skipped (opted out or no longer eligible)
    status: Mapped[str] = mapped_column(String(16))
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )


class EmailAsset(Base):
    """An image uploaded for campaigns; served publicly by its random id."""

    __tablename__ = "email_assets"

    id: Mapped[UUID] = mapped_column(Uuid(as_uuid=True), primary_key=True, default=uuid4)
    created_by_user_id: Mapped[UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"), nullable=True
    )
    title: Mapped[str] = mapped_column(String(120))
    description: Mapped[str] = mapped_column(Text, default="")
    content_type: Mapped[str] = mapped_column(String(32))
    width: Mapped[int] = mapped_column(Integer)
    height: Mapped[int] = mapped_column(Integer)
    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.now(UTC)
    )
